// BinaryIndex is the persistent, backend-neutral evidence pack for one binary,
// stored under <home>/cases/<case>/ghidra/<sha16>/index.json.
type BinaryIndex struct {
	Path        string         `json:"path"`
	SHA256      string         `json:"sha256"`
	Size        int64          `json:"size"`
	Format      string         `json:"format"`
	Arch        string         `json:"arch"`
	ImageBase   string         `json:"image_base,omitempty"`
	EntryPoint  string         `json:"entry_point,omitempty"`
	Backend     string         `json:"backend"` // ghidra-headless | rizin | native-static | imported-json
	GeneratedAt string         `json:"generated_at"`
	IndexPath   string         `json:"index_path"`
	ScriptPath  string         `json:"ghidra_script_path"`
	Functions   []FuncRecord   `json:"functions"`
	Imports     []ImportRecord `json:"imports"`
	Exports     []ExportRecord `json:"exports"`
	Strings     []StringRecord `json:"strings"`
	Xrefs       []XrefRecord   `json:"xrefs"`
	Notes       []string       `json:"notes,omitempty"`
}

// FuncRecord describes one function in the binary index.
type FuncRecord struct {
	Name       string   `json:"name"`
	Address    string   `json:"address"`
	Size       uint64   `json:"size,omitempty"`
	Signature  string   `json:"signature,omitempty"`
	Section    string   `json:"section,omitempty"`
	IsExternal bool     `json:"is_external,omitempty"`
	IsThunk    bool     `json:"is_thunk,omitempty"`
	Callers    []string `json:"callers,omitempty"`
	Callees    []string `json:"callees,omitempty"`
	Decompiled string   `json:"decompiled,omitempty"`
}

// ImportRecord describes an imported symbol.
type ImportRecord struct {
	Library string `json:"library,omitempty"`
	Name    string `json:"name"`
	Address string `json:"address,omitempty"`
}

// ExportRecord describes an exported symbol.
type ExportRecord struct {
	Name    string `json:"name"`
	Ordinal uint32 `json:"ordinal,omitempty"`
	Address string `json:"address"`
}

// StringRecord describes an indexed string literal.
type StringRecord struct {
	Offset   int64    `json:"offset"`
	Encoding string   `json:"encoding"`
	Value    string   `json:"value"`
	Xrefs    []string `json:"xrefs,omitempty"`
}

// XrefRecord describes a cross-reference edge (caller -> callee or code -> data).
type XrefRecord struct {
	From string `json:"from"`
	To   string `json:"to"`
	Kind string `json:"kind"` // call | data
}

// GhidraExportRequest parameters for re_ghidra_export.
type GhidraExportRequest struct {
	Case           string `json:"case,omitempty"`
	Path           string `json:"path"`
	Backend        string `json:"backend,omitempty"`     // auto (default) | ghidra | rizin | native
	ImportJSON     string `json:"import_json,omitempty"` // optional external JSON to ingest into cache
	Force          bool   `json:"force,omitempty"`       // re-run export even if cached index.json exists
	DecompileLimit int    `json:"decompile_limit,omitempty"`
	TimeoutS       int    `json:"timeout_s,omitempty"`
	View           string `json:"view,omitempty"`   // overview (default) | functions | function_detail | imports | exports | strings | xrefs
	Target         string `json:"target,omitempty"` // function name or address for function_detail
	Filter         string `json:"filter,omitempty"` // regexp filter for list views
	Offset         int    `json:"offset,omitempty"`
	Limit          int    `json:"limit,omitempty"`
}

const ghidraJavaScript = `// Autogenerated by agentgo-re (re_ghidra_export).
// Usage with analyzeHeadless:
//   analyzeHeadless <projDir> <projName> -import <binary> -scriptPath <dir> -postScript AgentgoExport.java <out.json> [decompileLimit] -deleteProject
//@category AgentGo
import java.io.File;
import java.io.FileWriter;
import java.io.PrintWriter;
import java.util.*;
import ghidra.app.decompiler.DecompInterface;
import ghidra.app.decompiler.DecompileResults;
import ghidra.app.script.GhidraScript;
import ghidra.program.model.address.Address;
import ghidra.program.model.listing.*;
import ghidra.program.model.symbol.*;

public class AgentgoExport extends GhidraScript {
    private static String esc(String s) {
        if (s == null) return "";
        return s.replace("\\", "\\\\").replace("\"", "\\\"").replace("\r", "\\r").replace("\n", "\\n").replace("\t", "\\t");
    }

    @Override
    public void run() throws Exception {
        String[] args = getScriptArgs();
        if (args.length < 1) {
            println("AgentgoExport: output path argument required");
            return;
        }
        String outPath = args[0];
        int decompLimit = 60;
        if (args.length >= 2) {
            try { decompLimit = Integer.parseInt(args[1]); } catch (Exception ignored) {}
        }

        DecompInterface decomp = new DecompInterface();
        decomp.openProgram(currentProgram);

        FunctionManager fm = currentProgram.getFunctionManager();
        List<Function> funcs = new ArrayList<>();
        FunctionIterator fit = fm.getFunctions(true);
        while (fit.hasNext() && !monitor.isCancelled()) {
            funcs.add(fit.next());
        }
        funcs.sort((a, b) -> Long.compare(b.getBody().getNumAddresses(), a.getBody().getNumAddresses()));
        Set<Address> toDecomp = new HashSet<>();
        for (Function f : funcs) {
            if (toDecomp.size() >= decompLimit) break;
            if (!f.isExternal() && !f.isThunk()) {
                toDecomp.add(f.getEntryPoint());
            }
        }
        funcs.sort(Comparator.comparing(Function::getEntryPoint));

        try (PrintWriter out = new PrintWriter(new FileWriter(new File(outPath)))) {
            out.println("{");
            out.println("  \"backend\": \"ghidra-headless\",");
            out.println("  \"arch\": \"" + esc(currentProgram.getLanguageID().toString()) + "\",");
            out.println("  \"image_base\": \"0x" + currentProgram.getImageBase().toString() + "\",");
            out.println("  \"functions\": [");
            for (int i = 0; i < funcs.size(); i++) {
                Function f = funcs.get(i);
                String cCode = "";
                if (toDecomp.contains(f.getEntryPoint())) {
                    DecompileResults res = decomp.decompileFunction(f, 15, monitor);
                    if (res != null && res.decompileCompleted() && res.getDecompiledFunction() != null) {
                        cCode = res.getDecompiledFunction().getC();
                    }
                }
                Set<Function> callers = f.getCallingFunctions(monitor);
                Set<Function> callees = f.getCalledFunctions(monitor);
                out.print("    {\"name\":\"" + esc(f.getName()) + "\",\"address\":\"0x" + f.getEntryPoint().toString()
                    + "\",\"size\":" + f.getBody().getNumAddresses()
                    + ",\"signature\":\"" + esc(f.getPrototypeString(false, false)) + "\""
                    + ",\"is_external\":" + f.isExternal() + ",\"is_thunk\":" + f.isThunk()
                    + ",\"callers\":" + toJsonArray(callers) + ",\"callees\":" + toJsonArray(callees)
                    + ",\"decompiled\":\"" + esc(cCode) + "\"}");
                out.println(i + 1 < funcs.size() ? "," : "");
            }
            out.println("  ]");
            out.println("}");
        }
        decomp.dispose();
    }

    private String toJsonArray(Set<Function> set) {
        StringBuilder sb = new StringBuilder("[");
        int k = 0;
        for (Function f : set) {
            if (k >= 32) break;
            if (k++ > 0) sb.append(",");
            sb.append("\"").append(esc(f.getName())).append("@0x").append(f.getEntryPoint().toString()).append("\"");
        }
        sb.append("]");
        return sb.toString();
    }
}
`

// ExportOrQueryBinary builds or loads the persistent BinaryIndex for req.Path, then answers req.View with paging.
func (k *Kit) ExportOrQueryBinary(req GhidraExportRequest) (Reply, error) {
	p, err := absPath(req.Path)
	if err != nil {
		return Reply{}, err
	}
	req.Path = p
	idx, cached, err := k.buildOrLoadIndex(req)
	if err != nil {
		return Reply{}, err
	}
	return queryBinaryIndex(idx, cached, req)
}

func (k *Kit) buildOrLoadIndex(req GhidraExportRequest) (*BinaryIndex, bool, error) {
	triage, err := TriageFile(req.Path, 0)
	if err != nil {
		return nil, false, err
	}
	shaPrefix := triage.SHA256
	if len(shaPrefix) > 16 {
		shaPrefix = shaPrefix[:16]
	}
	cDir, err := caseDir(k.homeDir(), req.Case)
	if err != nil {
		return nil, false, err
	}
	workDir := filepath.Join(cDir, "ghidra", shaPrefix)
	if err := os.MkdirAll(workDir, 0o755); err != nil {
		return nil, false, err
	}
	scriptPath := filepath.Join(workDir, "AgentgoExport.java")
	_ = os.WriteFile(scriptPath, []byte(ghidraJavaScript), 0o644)
	indexPath := filepath.Join(workDir, "index.json")

	// 1. Optional ingest from an external JSON file.
	if strings.TrimSpace(req.ImportJSON) != "" {
		impPath, err := absPath(req.ImportJSON)
		if err != nil {
			return nil, false, err
		}
		raw, err := os.ReadFile(impPath)
		if err != nil {
			return nil, false, err
		}
		var idx BinaryIndex
		if err := json.Unmarshal(bytesTrimBOM(raw), &idx); err != nil {
			return nil, false, fmt.Errorf("parse import_json: %w", err)
		}
		populateIndexIdentity(&idx, triage, indexPath, scriptPath, "imported-json")
		if err := saveBinaryIndex(indexPath, &idx); err != nil {
			return nil, false, err
		}
		return &idx, false, nil
	}

	// 2. Load from persistent cache if present and not forced.
	if !req.Force {
		if raw, err := os.ReadFile(indexPath); err == nil {
			var idx BinaryIndex
			if json.Unmarshal(raw, &idx) == nil && len(idx.Functions)+len(idx.Imports)+len(idx.Exports)+len(idx.Strings) > 0 {
				idx.IndexPath = indexPath
				idx.ScriptPath = scriptPath
				return &idx, true, nil
			}
		}
	}

	wantBackend := strings.ToLower(strings.TrimSpace(req.Backend))
	if wantBackend == "" {
		wantBackend = "auto"
	}
	decompLimit := req.DecompileLimit
	if decompLimit <= 0 {
		decompLimit = 60
	}
	timeout := time.Duration(req.TimeoutS) * time.Second
	if timeout <= 0 {
		timeout = 300 * time.Second
	}

	// 3. Try Ghidra Headless if available and requested.
	if wantBackend == "auto" || wantBackend == "ghidra" || wantBackend == "ghidra-headless" {
		if ghidraExe := k.resolveCatalogTool("ghidra-headless"); ghidraExe != "" {
			idx, gerr := runGhidraHeadlessExport(ghidraExe, workDir, scriptPath, indexPath, triage, decompLimit, timeout)
			if gerr == nil {
				return idx, false, nil
			}
			if wantBackend == "ghidra" || wantBackend == "ghidra-headless" {
				return nil, false, gerr
			}
		} else if wantBackend == "ghidra" || wantBackend == "ghidra-headless" {
			return nil, false, fmt.Errorf("ghidra-headless not found; set RE_TOOL_GHIDRA_HEADLESS or use backend=auto")
		}
	}

	// 4. Try Rizin / r2 if available and requested.
	if wantBackend == "auto" || wantBackend == "rizin" || wantBackend == "r2" {
		if rzExe := k.resolveCatalogTool("rizin"); rzExe != "" {
			if idx, rerr := runRizinExport(rzExe, indexPath, scriptPath, triage, timeout); rerr == nil {
				return idx, false, nil
			}
		}
	}

	// 5. Pure-Go static binary indexer (PE .pdata/exports/imports/call-xrefs, ELF symtab/dynsym, strings).
	idx, err := buildNativeStaticIndex(triage, indexPath, scriptPath)
	if err != nil {
		return nil, false, err
	}
	if err := saveBinaryIndex(indexPath, idx); err != nil {
		return nil, false, err
	}
	return idx, false, nil
}

func (k *Kit) resolveCatalogTool(name string) string {
	if k.Box == nil {
		return ""
	}
	for _, s := range k.Box.Probe(false) {
		if s.Name == name {
			return s.Resolved
		}
	}
	return ""
}

func populateIndexIdentity(idx *BinaryIndex, t *Triage, indexPath, scriptPath, defaultBackend string) {
	idx.Path = t.Path
	idx.SHA256 = t.SHA256
	idx.Size = t.Size
	if idx.Format == "" {
		idx.Format = t.Kind
	}
	if idx.Backend == "" {
		idx.Backend = defaultBackend
	}
	idx.GeneratedAt = time.Now().Format(time.RFC3339)
	idx.IndexPath = indexPath
	idx.ScriptPath = scriptPath
}

func saveBinaryIndex(path string, idx *BinaryIndex) error {
	b, err := json.MarshalIndent(idx, "", " ")
	if err != nil {
		return err
	}
	return os.WriteFile(path, b, 0o644)
}

func runGhidraHeadlessExport(exe, workDir, scriptPath, indexPath string, t *Triage, decompLimit int, timeout time.Duration) (*BinaryIndex, error) {
	projDir := filepath.Join(workDir, "proj")
	_ = os.MkdirAll(projDir, 0o755)
	rawOut := filepath.Join(workDir, "ghidra_raw.json")
	_ = os.Remove(rawOut)

	ctx, cancel := context.WithTimeout(context.Background(), timeout)
	defer cancel()
	args := []string{
		projDir, "agentgo_proj",
		"-import", t.Path,
		"-scriptPath", workDir,
		"-postScript", filepath.Base(scriptPath), rawOut, fmt.Sprintf("%d", decompLimit),
		"-deleteProject",
	}
	cmd := exec.CommandContext(ctx, exe, args...)
	processutil.HideWindow(cmd)
	out, err := cmd.CombinedOutput()
	if err != nil {
		return nil, fmt.Errorf("ghidra-headless failed: %v (%s)", err, hexPreview(out, 200))
	}
	raw, err := os.ReadFile(rawOut)
	if err != nil {
		return nil, fmt.Errorf("ghidra script did not write %s: %w", rawOut, err)
	}
	var idx BinaryIndex
	if err := json.Unmarshal(raw, &idx); err != nil {
		return nil, fmt.Errorf("parse ghidra output: %w", err)
	}
	// Supplement imports/exports/strings from native static pass if not populated.
	nat, _ := buildNativeStaticIndex(t, indexPath, scriptPath)
	if nat != nil {
		if len(idx.Imports) == 0 {
			idx.Imports = nat.Imports
		}
		if len(idx.Exports) == 0 {
			idx.Exports = nat.Exports
		}
		if len(idx.Strings) == 0 {
			idx.Strings = nat.Strings
		}
	}
	populateIndexIdentity(&idx, t, indexPath, scriptPath, "ghidra-headless")
	if err := saveBinaryIndex(indexPath, &idx); err != nil {
		return nil, err
	}
	return &idx, nil
}

func runRizinExport(exe, indexPath, scriptPath string, t *Triage, timeout time.Duration) (*BinaryIndex, error) {
	ctx, cancel := context.WithTimeout(context.Background(), timeout)
	defer cancel()
	cmd := exec.CommandContext(ctx, exe, "-2", "-qc", "aaa; aflj", t.Path)
	processutil.HideWindow(cmd)
	out, err := cmd.Output()
	if err != nil {
		return nil, err
	}
	var rzFuncs []struct {
		Name   string `json:"name"`
		Offset uint64 `json:"offset"`
		Size   uint64 `json:"size"`
	}
	if err := json.Unmarshal(bytesTrimBOM(out), &rzFuncs); err != nil {
		return nil, err
	}
	idx, err := buildNativeStaticIndex(t, indexPath, scriptPath)
	if err != nil {
		idx = &BinaryIndex{}
	}
	idx.Backend = "rizin"
	if len(rzFuncs) > 0 {
		idx.Functions = make([]FuncRecord, 0, len(rzFuncs))
		for _, rf := range rzFuncs {
			idx.Functions = append(idx.Functions, FuncRecord{
				Name:    rf.Name,
				Address: fmt.Sprintf("0x%x", rf.Offset),
				Size:    rf.Size,
			})
		}
	}
	populateIndexIdentity(idx, t, indexPath, scriptPath, "rizin")
	if err := saveBinaryIndex(indexPath, idx); err != nil {
		return nil, err
	}
	return idx, nil
}

// buildNativeStaticIndex recovers functions, exports, imports, call xrefs and strings
// in pure Go without requiring Ghidra or IDA to be installed.
func buildNativeStaticIndex(t *Triage, indexPath, scriptPath string) (*BinaryIndex, error) {
	idx := &BinaryIndex{
		Path:       t.Path,
		SHA256:     t.SHA256,
		Size:       t.Size,
		Format:     t.Kind,
		Backend:    "native-static",
		IndexPath:  indexPath,
		ScriptPath: scriptPath,
	}

	switch {
	case strings.HasPrefix(t.Kind, "pe"):
		indexPE(t.Path, idx)
	case t.Kind == "elf":
		indexELF(t.Path, idx)
	}

	// Extract up to 1500 strings for fast indexed search.
	if hits, _, _, err := ExtractStrings(t.Path, 0, 16<<20, 5, false, ""); err == nil {
		if len(hits) > 1500 {
			hits = hits[:1500]
		}
		for _, h := range hits {
			idx.Strings = append(idx.Strings, StringRecord{
				Offset:   h.Offset,
				Encoding: h.Enc,
				Value:    h.Text,
			})
		}
	}

	idx.Notes = append(idx.Notes,
		fmt.Sprintf("Headless Ghidra script generated at %s; run analyzeHeadless with -postScript AgentgoExport.java %s to enrich with decompiled C.", scriptPath, indexPath))
	populateIndexIdentity(idx, t, indexPath, scriptPath, "native-static")
	return idx, nil
}

func indexPE(path string, idx *BinaryIndex) {
	f, err := pe.Open(path)
	if err != nil {
		return
	}
	defer f.Close()

	var imgBase, entryRVA uint64
	var dirs []pe.DataDirectory
	switch oh := f.OptionalHeader.(type) {
	case *pe.OptionalHeader64:
		imgBase = oh.ImageBase
		entryRVA = uint64(oh.AddressOfEntryPoint)
		dirs = oh.DataDirectory[:]
		idx.Arch = "pe-x86_64"
	case *pe.OptionalHeader32:
		imgBase = uint64(oh.ImageBase)
		entryRVA = uint64(oh.AddressOfEntryPoint)
		dirs = oh.DataDirectory[:]
		idx.Arch = "pe-x86"
	}
	idx.ImageBase = fmt.Sprintf("0x%x", imgBase)
	if entryRVA != 0 {
		idx.EntryPoint = fmt.Sprintf("0x%x", imgBase+entryRVA)
	}

	// 1. Imports ("symbol:dll" from debug/pe).
	if syms, err := f.ImportedSymbols(); err == nil {
		for _, s := range syms {
			name, lib := s, ""
			if i := strings.LastIndexByte(s, ':'); i > 0 {
				name, lib = s[:i], s[i+1:]
			}
			idx.Imports = append(idx.Imports, ImportRecord{Library: lib, Name: name})
		}
	}

	funcByRVA := map[uint32]*FuncRecord{}
	addOrMergeFunc := func(rva uint32, name string, size uint64, secName string) *FuncRecord {
		if rva == 0 {
			return nil
		}
		if existing, ok := funcByRVA[rva]; ok {
			if strings.HasPrefix(existing.Name, "sub_") && name != "" && !strings.HasPrefix(name, "sub_") {
				existing.Name = name
			}
			if existing.Size == 0 && size > 0 {
				existing.Size = size
			}
			return existing
		}
		va := imgBase + uint64(rva)
		if name == "" {
			name = fmt.Sprintf("sub_%x", va)
		}
		rec := &FuncRecord{
			Name:    name,
			Address: fmt.Sprintf("0x%x", va),
			Size:    size,
			Section: secName,
		}
		funcByRVA[rva] = rec
		return rec
	}

	if entryRVA != 0 {
		addOrMergeFunc(uint32(entryRVA), "_entry", 0, ".text")
	}

	// 2. Parse Export Directory (DataDirectory[0]) directly from section bytes.
	if len(dirs) > 0 && dirs[0].VirtualAddress != 0 && dirs[0].Size >= 40 {
		expRVA := dirs[0].VirtualAddress
		if data, secBase := rvaSlice(f, expRVA, 40); len(data) >= 40 {
			_ = secBase
			numFuncs := le32(data[20:24])
			numNames := le32(data[24:28])
			addrFuncsRVA := le32(data[28:32])
			addrNamesRVA := le32(data[32:36])
			addrOrdsRVA := le32(data[36:40])
			ordinalBase := le32(data[16:20])

			nameByFuncIdx := map[uint32]string{}
			if numNames > 0 && numNames <= 65536 {
				namesBuf, _ := rvaSlice(f, addrNamesRVA, numNames*4)
				ordsBuf, _ := rvaSlice(f, addrOrdsRVA, numNames*2)
				if len(namesBuf) >= int(numNames*4) && len(ordsBuf) >= int(numNames*2) {
					for i := uint32(0); i < numNames; i++ {
						nRVA := le32(namesBuf[i*4:])
						ordIdx := uint32(le16(ordsBuf[i*2:]))
						if s := readCStringRVA(f, nRVA, 256); s != "" {
							nameByFuncIdx[ordIdx] = s
						}
					}
				}
			}
			if numFuncs > 0 && numFuncs <= 65536 {
				funcsBuf, _ := rvaSlice(f, addrFuncsRVA, numFuncs*4)
				if len(funcsBuf) >= int(numFuncs*4) {
					for i := uint32(0); i < numFuncs; i++ {
						fnRVA := le32(funcsBuf[i*4:])
						if fnRVA == 0 {
							continue
						}
						// Skip forwarder RVAs that point inside the export directory itself.
						if fnRVA >= expRVA && fnRVA < expRVA+dirs[0].Size {
							continue
						}
						name := nameByFuncIdx[i]
						if name == "" {
							name = fmt.Sprintf("ord_%d", ordinalBase+i)
						}
						va := imgBase + uint64(fnRVA)
						idx.Exports = append(idx.Exports, ExportRecord{
							Name:    name,
							Ordinal: ordinalBase + i,
							Address: fmt.Sprintf("0x%x", va),
						})
						addOrMergeFunc(fnRVA, name, 0, sectionNameForRVA(f, fnRVA))
					}
				}
			}
		}
	}

	// 3. Parse x64 Exception Directory (.pdata, DataDirectory[3]): each entry is 12 bytes
	// (BeginAddress RVA, EndAddress RVA, UnwindInfo RVA) giving exact function boundaries!
	if len(dirs) > 3 && dirs[3].VirtualAddress != 0 && dirs[3].Size >= 12 {
		pdata, _ := rvaSlice(f, dirs[3].VirtualAddress, min(dirs[3].Size, 4<<20))
		for off := 0; off+12 <= len(pdata); off += 12 {
			beginRVA := le32(pdata[off : off+4])
			endRVA := le32(pdata[off+4 : off+8])
			if beginRVA == 0 || endRVA <= beginRVA || endRVA-beginRVA > 16<<20 {
				continue
			}
			addOrMergeFunc(beginRVA, "", uint64(endRVA-beginRVA), sectionNameForRVA(f, beginRVA))
		}
	}

	// 4. COFF symbol table if present (MinGW/Go/unstripped PE).
	for _, sym := range f.Symbols {
		if sym.SectionNumber > 0 && int(sym.SectionNumber) <= len(f.Sections) && sym.Type == 0x20 {
			sec := f.Sections[sym.SectionNumber-1]
			rva := sec.VirtualAddress + sym.Value
			addOrMergeFunc(rva, sym.Name, 0, strings.TrimRight(sec.Name, "\x00"))
		}
	}

	// Collect and sort functions by RVA.
	rvas := make([]uint32, 0, len(funcByRVA))
	for rva := range funcByRVA {
		rvas = append(rvas, rva)
	}
	sort.Slice(rvas, func(i, j int) bool { return rvas[i] < rvas[j] })

	// 5. Scan executable sections for direct relative CALL (0xE8 rel32) to known function RVAs.
	for _, sec := range f.Sections {
		const imageScnMemExecute = 0x20000000
		if sec.Characteristics&imageScnMemExecute == 0 || sec.Size == 0 || sec.Size > 32<<20 {
			continue
		}
		code, err := sec.Data()
		if err != nil {
			continue
		}
		secRVA := sec.VirtualAddress
		for i := 0; i+5 <= len(code); i++ {
			if code[i] != 0xE8 {
				continue
			}
			rel := int32(le32(code[i+1 : i+5]))
			callSiteRVA := secRVA + uint32(i)
			targetRVA := uint32(int64(callSiteRVA) + 5 + int64(rel))
			callee, ok := funcByRVA[targetRVA]
			if !ok {
				continue
			}
			caller := findEnclosingFunc(rvas, funcByRVA, callSiteRVA)
			fromLabel := fmt.Sprintf("0x%x", imgBase+uint64(callSiteRVA))
			if caller != nil {
				fromLabel = caller.Name + "@" + caller.Address
				if len(caller.Callees) < 32 && !contains(caller.Callees, callee.Name) {
					caller.Callees = append(caller.Callees, callee.Name)
				}
				if len(callee.Callers) < 32 && !contains(callee.Callers, caller.Name) {
					callee.Callers = append(callee.Callers, caller.Name)
				}
			}
			if len(idx.Xrefs) < 4000 {
				idx.Xrefs = append(idx.Xrefs, XrefRecord{
					From: fromLabel,
					To:   callee.Name + "@" + callee.Address,
					Kind: "call",
				})
			}
		}
	}

	idx.Functions = make([]FuncRecord, 0, len(rvas))
	for _, rva := range rvas {
		idx.Functions = append(idx.Functions, *funcByRVA[rva])
	}
}

func findEnclosingFunc(sortedRVAs []uint32, byRVA map[uint32]*FuncRecord, rva uint32) *FuncRecord {
	i := sort.Search(len(sortedRVAs), func(i int) bool { return sortedRVAs[i] > rva }) - 1
	if i < 0 {
		return nil
	}
	fn := byRVA[sortedRVAs[i]]
	if fn.Size > 0 && uint64(rva) < uint64(sortedRVAs[i])+fn.Size {
		return fn
	}
	if fn.Size == 0 && rva-sortedRVAs[i] <= 4096 {
		return fn
	}
	return nil
}

func rvaSlice(f *pe.File, rva, length uint32) ([]byte, uint32) {
	for _, s := range f.Sections {
		if rva >= s.VirtualAddress && rva < s.VirtualAddress+max(s.VirtualSize, s.Size) {
			data, err := s.Data()
			if err != nil {
				return nil, 0
			}
			off := rva - s.VirtualAddress
			if off >= uint32(len(data)) {
				return nil, 0
			}
			end := min(uint32(len(data)), off+length)
			return data[off:end], s.VirtualAddress
		}
	}
	return nil, 0
}

func readCStringRVA(f *pe.File, rva, maxLen uint32) string {
	b, _ := rvaSlice(f, rva, maxLen)
	for i, c := range b {
		if c == 0 {
			return string(b[:i])
		}
		if c < 0x20 || c > 0x7e {
			return ""
		}
	}
	return ""
}

func sectionNameForRVA(f *pe.File, rva uint32) string {
	for _, s := range f.Sections {
		if rva >= s.VirtualAddress && rva < s.VirtualAddress+max(s.VirtualSize, s.Size) {
			return strings.TrimRight(s.Name, "\x00")
		}
	}
	return ""
}

func indexELF(path string, idx *BinaryIndex) {
	f, err := elf.Open(path)
	if err != nil {
		return
	}
	defer f.Close()
	idx.Arch = fmt.Sprintf("elf-%s-%s", f.Class.String(), f.Machine.String())
	if f.Entry != 0 {
		idx.EntryPoint = fmt.Sprintf("0x%x", f.Entry)
	}
	seenFunc := map[string]bool{}
	collectSyms := func(syms []elf.Symbol, dynamic bool) {
		for _, s := range syms {
			if s.Name == "" {
				continue
			}
			if s.Section == elf.SHN_UNDEF {
				if dynamic {
					idx.Imports = append(idx.Imports, ImportRecord{Library: s.Library, Name: s.Name})
				}
				continue
			}
			if elf.ST_TYPE(s.Info) == elf.STT_FUNC || s.Value != 0 {
				addr := fmt.Sprintf("0x%x", s.Value)
				if dynamic && elf.ST_BIND(s.Info) != elf.STB_LOCAL {
					idx.Exports = append(idx.Exports, ExportRecord{Name: s.Name, Address: addr})
				}
				if elf.ST_TYPE(s.Info) == elf.STT_FUNC && !seenFunc[addr+":"+s.Name] {
					seenFunc[addr+":"+s.Name] = true
					idx.Functions = append(idx.Functions, FuncRecord{
						Name:    s.Name,
						Address: addr,
						Size:    s.Size,
					})
				}
			}
		}
	}
	if dyns, err := f.DynamicSymbols(); err == nil {
		collectSyms(dyns, true)
	}
	if syms, err := f.Symbols(); err == nil {
		collectSyms(syms, false)
	}
}

func queryBinaryIndex(idx *BinaryIndex, cached bool, req GhidraExportRequest) (Reply, error) {
	view := strings.ToLower(strings.TrimSpace(req.View))
	if view == "" {
		view = "overview"
	}
	var re *regexp.Regexp
	if strings.TrimSpace(req.Filter) != "" {
		var err error
		re, err = regexp.Compile("(?i)" + req.Filter)
		if err != nil {
			return Reply{}, fmt.Errorf("invalid filter regexp: %w", err)
		}
	}
	limit := req.Limit
	if limit <= 0 {
		limit = 40
	}

	meta := map[string]any{
		"index_path":         idx.IndexPath,
		"ghidra_script_path": idx.ScriptPath,
		"backend":            idx.Backend,
		"cached":             cached,
		"sha256":             idx.SHA256,
		"view":               view,
	}
	limits := []string{
		fmt.Sprintf("index backend=%s (cached=%v); only indexed/paged items are returned", idx.Backend, cached),
	}
	if idx.Backend == "native-static" {
		limits = append(limits, "native-static backend recovers PE .pdata/exports/imports/E8-calls and ELF symbols without decompiler C output; install Ghidra and pass force=true for decompiled C")
	}

	switch view {
	case "overview":
		decompiledCount := 0
		for _, fn := range idx.Functions {
			if fn.Decompiled != "" {
				decompiledCount++
			}
		}
		top := append([]FuncRecord(nil), idx.Functions...)
		sort.Slice(top, func(i, j int) bool {
			if len(top[i].Callees)+len(top[i].Callers) != len(top[j].Callees)+len(top[j].Callers) {
				return len(top[i].Callees)+len(top[i].Callers) > len(top[j].Callees)+len(top[j].Callers)
			}
			return top[i].Size > top[j].Size
		})
		if len(top) > 15 {
			top = top[:15]
		}
		preview := make([]map[string]any, 0, len(top))
		for _, fn := range top {
			preview = append(preview, map[string]any{
				"name":           fn.Name,
				"address":        fn.Address,
				"size":           fn.Size,
				"callers":        len(fn.Callers),
				"callees":        len(fn.Callees),
				"has_decompiled": fn.Decompiled != "",
			})
		}
		return Reply{
			Facts: map[string]any{
				"path":               idx.Path,
				"format":             idx.Format,
				"arch":               idx.Arch,
				"image_base":         idx.ImageBase,
				"entry_point":        idx.EntryPoint,
				"backend":            idx.Backend,
				"cached":             cached,
				"index_path":         idx.IndexPath,
				"ghidra_script_path": idx.ScriptPath,
				"function_count":     len(idx.Functions),
				"decompiled_count":   decompiledCount,
				"import_count":       len(idx.Imports),
				"export_count":       len(idx.Exports),
				"string_count":       len(idx.Strings),
				"xref_count":         len(idx.Xrefs),
				"top_functions":      preview,
				"notes":              idx.Notes,
			},
			Limits: limits,
			Next: []string{
				"re_ghidra_export view=functions filter=... to search functions",
				"re_ghidra_export view=function_detail target=<name|address> to inspect callers/callees/decompiled code",
				"re_ghidra_export view=exports or view=imports or view=xrefs",
			},
		}, nil

	case "functions":
		var hits []FuncRecord
		for _, fn := range idx.Functions {
			if re != nil && !re.MatchString(fn.Name+" "+fn.Address+" "+fn.Signature) {
				continue
			}
			slim := fn
			slim.Decompiled = "" // omit full C body in list view; fetch via function_detail
			hits = append(hits, slim)
		}
		lo, hi, pg := page(len(hits), req.Offset, limit)
		return Reply{Facts: hits[lo:hi], Paging: pg, Extra: meta, Limits: limits}, nil

	case "function_detail":
		target := strings.ToLower(strings.TrimSpace(req.Target))
		if target == "" {
			return Reply{}, fmt.Errorf("target (function name or address) is required for view=function_detail")
		}
		var exact *FuncRecord
		var partial []*FuncRecord
		for i := range idx.Functions {
			fn := &idx.Functions[i]
			if strings.ToLower(fn.Name) == target || strings.ToLower(fn.Address) == target {
				exact = fn
				break
			}
			if strings.Contains(strings.ToLower(fn.Name), target) || strings.Contains(strings.ToLower(fn.Address), target) {
				partial = append(partial, fn)
			}
		}
		if exact == nil && len(partial) > 0 {
			exact = partial[0]
		}
		if exact == nil {
			return Reply{}, fmt.Errorf("function %q not found in index (%d functions indexed)", req.Target, len(idx.Functions))
		}
		var xrefs []XrefRecord
		for _, x := range idx.Xrefs {
			if strings.Contains(strings.ToLower(x.From), strings.ToLower(exact.Name)) ||
				strings.Contains(strings.ToLower(x.To), strings.ToLower(exact.Name)) ||
				strings.Contains(strings.ToLower(x.From), strings.ToLower(exact.Address)) ||
				strings.Contains(strings.ToLower(x.To), strings.ToLower(exact.Address)) {
				xrefs = append(xrefs, x)
				if len(xrefs) >= 50 {
					break
				}
			}
		}
		return Reply{
			Facts: map[string]any{
				"function": exact,
				"xrefs":    xrefs,
			},
			Extra:  meta,
			Limits: limits,
		}, nil

	case "imports":
		var hits []ImportRecord
		for _, im := range idx.Imports {
			if re != nil && !re.MatchString(im.Library+" "+im.Name+" "+im.Address) {
				continue
			}
			hits = append(hits, im)
		}
		lo, hi, pg := page(len(hits), req.Offset, limit)
		return Reply{Facts: hits[lo:hi], Paging: pg, Extra: meta, Limits: limits}, nil

	case "exports":
		var hits []ExportRecord
		for _, ex := range idx.Exports {
			if re != nil && !re.MatchString(ex.Name+" "+ex.Address) {
				continue
			}
			hits = append(hits, ex)
		}
		lo, hi, pg := page(len(hits), req.Offset, limit)
		return Reply{Facts: hits[lo:hi], Paging: pg, Extra: meta, Limits: limits}, nil

	case "strings":
		var hits []StringRecord
		for _, st := range idx.Strings {
			if re != nil && !re.MatchString(st.Value) {
				continue
			}
			hits = append(hits, st)
		}
		lo, hi, pg := page(len(hits), req.Offset, limit)
		return Reply{Facts: hits[lo:hi], Paging: pg, Extra: meta, Limits: limits}, nil

	case "xrefs":
		var hits []XrefRecord
		for _, x := range idx.Xrefs {
			if re != nil && !re.MatchString(x.From+" "+x.To+" "+x.Kind) {
				continue
			}
			hits = append(hits, x)
		}
		lo, hi, pg := page(len(hits), req.Offset, limit)
		return Reply{Facts: hits[lo:hi], Paging: pg, Extra: meta, Limits: limits}, nil

	default:
		return Reply{}, fmt.Errorf("unknown view %q (want overview|functions|function_detail|imports|exports|strings|xrefs)", req.View)
	}
}
